const monthsAgo = (m: number, dayOfMonth = 14) => {
  const now = new Date();
  const target = new Date(now.getFullYear(), now.getMonth() - m, Math.min(dayOfMonth, 26), 10, 30, 0);
  return target.toISOString();
};

